import numpy as np

einsum = lambda *args, **kwargs: np.einsum(*args, **kwargs, optimize=True)


class _DSRGHelper:
    """Spin-adapted DSRG contraction kernels.

    One-body operators are stored as their hole-particle blocks and two-body
    operators as the nine hole-hole-particle-particle blocks that are unique
    under the pair exchange X[ijab] = X[jiba]. Every operator these kernels
    take or produce is Hermitian, so the particle-hole blocks and the other
    member of each exchange pair are read as transposes of the stored ones.

    A commutator kernel accumulates [H, T] + [H, T]^dagger, the off-diagonal
    part of [H, T - T^dagger], into the stored blocks of its result. With
    store_large=False, H_T_C0 and H_T_C1_aa skip the terms of the ccav, ccvv
    and cavv blocks.
    """

    # elements of B['vv'] contracted at a time by the streamed kernels
    _chunk = 2**23

    def __init__(self, dsrg_obj):
        self.ncore = dsrg_obj.ncore
        self.nact = dsrg_obj.nact
        self.nvirt = dsrg_obj.nvirt

        self.hp_1_labels = ["ca", "cv", "av"]
        self.hp_2_labels = [
            "ccaa",
            "ccav",
            "ccvv",
            "caaa",
            "caav",
            "cava",
            "cavv",
            "aaav",
            "aavv",
        ]
        # DSRG-MRPT2 leaves out ccav, ccvv and cavv, the blocks with at most
        # one active index, and streams their terms (store_large=False).
        self.hp_2_small_labels = ["ccaa", "caaa", "caav", "cava", "aaav", "aavv"]
        self.non_od_1_labels = ["cc", "aa", "vv"]
        # The non-off-diagonal two-body blocks the kernels below read, one of
        # each Hermitian/exchange pair. Blocks with three or four virtual
        # indices are streamed from the three-index integrals by the
        # *_non_od_large kernels and never built.
        self.non_od_2_labels = [
            "cccc",
            "ccca",
            "cccv",
            "caca",
            "cacv",
            "caac",
            "cavc",
            "cvcv",
            "cvaa",
            "cvav",
            "cvvc",
            "cvva",
            "aaaa",
            "avav",
            "avva",
        ]
        self.dims = {"c": self.ncore, "a": self.nact, "v": self.nvirt}

    def make_tensor(self, labels):
        return {label: np.zeros(tuple(self.dims[l] for l in label)) for label in labels}

    # fmt: off
    @staticmethod
    def H_T_C0(F, V, T1, T2, S2, cumulants, scale=1.0, store_large=True):
        # 32 lines

        g1 = cumulants['gamma1']
        e1 = cumulants['eta1']
        l2 = cumulants['lambda2']
        l3 = cumulants['lambda3']

        C0 = 0.0
        C0 += scale * +2.000 * einsum('ma,ma->', F['ca'], T1['ca'])
        C0 += scale * +2.000 * einsum('ma,ma->', F['cv'], T1['cv'])
        C0 += scale * +1.000 * einsum('ve,ue,uv->', F['av'], T1['av'], g1)
        C0 += scale * -1.000 * einsum('mu,mv,uv->', F['ca'], T1['ca'], g1)
        C0 += scale * +1.000 * einsum('xe,vuye,uvxy->', F['av'], T2['aaav'], l2)
        C0 += scale * -1.000 * einsum('mv,muyx,uvxy->', F['ca'], T2['caaa'], l2)
        C0 += scale * +1.000 * einsum('yxve,ue,uvxy->', V['aaav'], T1['av'], l2)
        C0 += scale * -1.000 * einsum('myuv,mx,uvxy->', V['caaa'], T1['ca'], l2)
        C0 += scale * +0.250 * einsum('xuef,yvef,uv,xy->', V['aavv'], S2['aavv'], g1, g1)
        C0 += scale * +0.250 * einsum('mnvy,mnux,uv,xy->', V['ccaa'], S2['ccaa'], e1, e1)
        C0 += scale * +0.500 * einsum('mxve,myue,uv,xy->', V['caav'], S2['caav'], e1, g1)
        C0 += scale * +0.500 * einsum('mxev,myeu,uv,xy->', V['cava'], S2['cava'], e1, g1)
        C0 += scale * +0.250 * einsum('xwve,yzue,wz,uv,xy->', V['aaav'], S2['aaav'], g1, e1, g1)
        C0 += scale * +0.250 * einsum('mxvz,myuw,wz,uv,xy->', V['caaa'], S2['caaa'], e1, e1, g1)
        C0 += scale * +0.500 * einsum('mnuv,mnxy,uvxy->', V['ccaa'], T2['ccaa'], l2)
        C0 += scale * +0.500 * einsum('mwuv,mzxy,wz,uvxy->', V['caaa'], T2['caaa'], g1, l2)
        C0 += scale * +0.500 * einsum('xyef,uvef,uvxy->', V['aavv'], T2['aavv'], l2)
        C0 += scale * +0.500 * einsum('yxze,vuwe,wz,uvxy->', V['aaav'], T2['aaav'], e1, l2)
        C0 += scale * +1.000 * einsum('mxeu,mvey,uvxy->', V['cava'], S2['cava'], l2)
        C0 += scale * -1.000 * einsum('mxue,mvey,uvxy->', V['caav'], T2['cava'], l2)
        C0 += scale * -1.000 * einsum('mxve,muye,uvxy->', V['caav'], T2['caav'], l2)
        C0 += scale * +0.500 * einsum('xwue,vzye,wz,uvxy->', V['aaav'], S2['aaav'], g1, l2)
        C0 += scale * -0.500 * einsum('wxue,vzye,wz,uvxy->', V['aaav'], T2['aaav'], g1, l2)
        C0 += scale * -0.500 * einsum('wxve,zuye,wz,uvxy->', V['aaav'], T2['aaav'], g1, l2)
        C0 += scale * +0.500 * einsum('mxwu,mvzy,wz,uvxy->', V['caaa'], S2['caaa'], e1, l2)
        C0 += scale * -0.500 * einsum('mxuw,mvzy,wz,uvxy->', V['caaa'], T2['caaa'], e1, l2)
        C0 += scale * -0.500 * einsum('mxvw,muyz,wz,uvxy->', V['caaa'], T2['caaa'], e1, l2)
        if store_large:
            C0 += scale * +1.000 * einsum('mnef,mnef->', V['ccvv'], S2['ccvv'])
            C0 += scale * +1.000 * einsum('muef,mvef,uv->', V['cavv'], S2['cavv'], g1)
            C0 += scale * +1.000 * einsum('mnve,mnue,uv->', V['ccav'], S2['ccav'], e1)
        if l3 is not None:
            C0 += scale * +1.000 * einsum('yxwe,vuze,xyzuwv->', V['aaav'], T2['aaav'], l3)
            C0 += scale * -1.000 * einsum('mzuv,mwxy,xyzuwv->', V['caaa'], T2['caaa'], l3)

        return C0

