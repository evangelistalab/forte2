"""Elementary-block contraction kernels for spin-free DSRG-MRPT3.

Generated by codegen/gen_kernels.py from the working equations in codegen/terms.py,
which hold them once in composite hole/particle/general indices. Every term is
expanded over the elementary core/active/virtual blocks and the combinations
that cannot contribute are dropped: an amplitude block outside its
hole-particle support, or an output block that is not off-diagonal.

Do not edit by hand. Change codegen/terms.py and regenerate.
"""

import numpy as np

# Blocking makes most contractions small, and for a small one numpy spends
# longer deriving a contraction path than performing the contraction. Choosing
# per call is worth about 10% end to end (N2/cc-pVTZ 4.6 -> 4.0 s; cc-pVDZ
# 1.66 -> 1.44 s) -- far less than a single-contraction microbenchmark suggests,
# since most of the work sits in the contractions large enough to take the
# optimized path either way.
#
# The test is the cost of contracting naively: the product over the union of the
# indices, not the operand sizes, which understate it by orders of magnitude.
# Because that is a count of operations rather than a size, the threshold does
# not need retuning per system. Measured optimum, flat to within a few percent
# between 20_000 and 200_000 and rising sharply above it (2e6 -> 5.2 s,
# 2e7 -> 12.4 s at cc-pVTZ).
#
# Three or more operands always go through the optimizer: an unoptimized
# multi-operand einsum contracts over every index at once, which is the trap
# `_df` sidesteps.
_NAIVE_MAX = 200_000


def einsum(spec, *ops, **kwargs):
    if len(ops) == 2:
        lhs = spec.split("->")[0]
        dims = {}
        for idx, o in zip(lhs.split(","), ops):
            for c, n in zip(idx, o.shape):
                dims[c] = n
        work = 1
        for n in dims.values():
            work *= n
        if work <= _NAIVE_MAX:
            return np.einsum(spec, *ops, optimize=False, **kwargs)
    return np.einsum(spec, *ops, optimize=True, **kwargs)


class _DSRGBlockHelper:
    """Spin-free DSRG-MRPT3 commutators, contracted block by block.

    Operators are dicts keyed by an elementary block label whose characters
    correspond one for one to the tensor's indices, so every contraction runs
    on a contiguous array and no composite index is ever sliced.

    A kernel whose operand is itself a commutator has an ``_od`` variant, pruned
    to the off-diagonal blocks such an operand can occupy -- the same split the
    two-component code makes with its ``_non_od`` kernels.
    """

